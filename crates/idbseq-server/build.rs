//! Embed the admin console (US-0046): list every file under `ui/dist` (the
//! committed output of `npm run build` in `ui/`) as `ui::FILES`. Building the
//! server never needs Node.
// A build script reports failure by panicking: the message stops the build.
#![allow(clippy::expect_used, clippy::panic)]

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

const DIST: &str = "ui/dist";

fn main() {
    println!("cargo:rerun-if-changed={DIST}");
    let root = Path::new(&env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR")).join(DIST);
    let mut files = Vec::new();
    collect(&root, &root, &mut files);
    files.sort();
    assert!(
        files.iter().any(|(path, _)| path == "index.html"),
        "{} has no index.html: run `npm ci && npm run build` in crates/idbseq-server/ui",
        root.display()
    );

    let mut source = String::from(
        "/// Every file of the console, generated by build.rs from `ui/dist`.\npub const FILES: &[UiFile] = &[\n",
    );
    for (path, absolute) in &files {
        writeln!(
            source,
            "    UiFile {{ path: {path:?}, content_type: {:?}, body: include_bytes!({:?}) }},",
            content_type(path),
            absolute.display().to_string()
        )
        .expect("write to String");
    }
    source.push_str("];\n");
    let out = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join("ui_files.rs");
    fs::write(out, source).expect("write ui_files.rs");
}

fn collect(root: &Path, dir: &Path, files: &mut Vec<(String, PathBuf)>) {
    let entries = fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
    for entry in entries {
        let path = entry.expect("directory entry").path();
        if path.is_dir() {
            collect(root, &path, files);
        } else {
            let relative = path.strip_prefix(root).expect("under root");
            let web_path = relative
                .components()
                .map(|c| c.as_os_str().to_string_lossy())
                .collect::<Vec<_>>()
                .join("/");
            files.push((web_path, path));
        }
    }
}

fn content_type(path: &str) -> &'static str {
    match path
        .rsplit_once('.')
        .map(|(_, ext)| ext.to_ascii_lowercase())
        .as_deref()
    {
        Some("html") => "text/html; charset=utf-8",
        Some("js" | "mjs") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("ico") => "image/x-icon",
        Some("woff2") => "font/woff2",
        Some("json") => "application/json",
        Some("txt") => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}
